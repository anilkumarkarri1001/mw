# Request model for decrypting an image using the encrypted URL, password, and mobile number.
class DecryptImageRequest(BaseModel):
    encrypted_image_url: str = Field(..., description="Encrypted image URL (Base64 AES-GCM string)")
    password: str = Field(..., description="Password: DOB year + last 5 digits of mobile (e.g. 199043210)")
    mobile: str = Field(..., description="User mobile number")

@router.post(
    "/decrypt-image",
    summary="Decrypt User Image URL",
    description="Validates user password (DOB year + last 5 digits of mobile) and decrypts the encrypted image URL.",
    response_model=Dict[str, Any]
)
async def decrypt_user_image(
    payload: DecryptImageRequest,
    x_caller_mobile: Optional[str] = Header(None),
    verified_mobile: Optional[str] = Depends(get_verified_mobile)  # <-- Injects token validation
):
    """Verify password against DOB year + last 5 mobile digits, then decrypt image URL."""
    logger.info(f"### decrypt_user_image request received for mobile: {payload.mobile}")
    # 1. Authentication validation via resolve_caller_mobile
    caller_mobile = resolve_caller_mobile(x_caller_mobile or payload.mobile, verified_mobile)
    try:
        driver = get_shared_driver()
        with driver.session() as session:
            # Authorization: Ensure caller is the user themselves or staff/admin
            require_self_or_staff(session, caller_mobile, payload.mobile)
            # 2. Fetch user's date of birth and mobile from Neo4j
            record = session.run(
                "MATCH (u:User {mobile: $mobile}) RETURN u.dob AS dob, u.mobile AS mobile",
                mobile=payload.mobile
            ).single()

            if not record:
                logger.warning(f"### decrypt_user_image user not found for mobile: {payload.mobile}")
                return {"statuscode": 404, "status": "error", "message": "User not found"}
            dob = record.get("dob")
            if not dob:
                logger.warning(f"### decrypt_user_image dob not found for user: {payload.mobile}")
                return {"statuscode": 400, "status": "error", "message": "Date of birth not found for this user"}
            
            # 3. Extract DOB Year (supports '1990-01-15' string or Neo4j Date object)
            dob_str = str(dob).strip()
            dob_year = str(dob.year) if hasattr(dob, "year") else dob_str.split("-")[0].strip()
            
            # 4. Extract last 5 digits of mobile number
            clean_mobile = str(record.get("mobile") or payload.mobile).strip()
            if len(clean_mobile) < 5:
                logger.warning(f"### decrypt_user_image invalid mobile format for mobile: {payload.mobile}")
                return {"statuscode": 400, "status": "error", "message": "Invalid mobile number"}
            last_5_digits = clean_mobile[-5:]
            expected_password = f"{dob_year}{last_5_digits}"
            
            # 5. Compare user entered password with expected password
            if str(payload.password).strip() != expected_password:
                logger.warning(f"### decrypt_user_image invalid password attempt for mobile: {payload.mobile}")
                return {"statuscode": 401, "status": "error", "message": "Invalid password"}
            
            # 6. Decrypt the image URL
            try:
                decrypted_url = decrypt_value(payload.encrypted_image_url)
                return {
                    "statuscode": 200,
                    "status": "success",
                    "message": "Image URL decrypted successfully",
                    "image_url": decrypted_url
                }
            except Exception as decrypt_error:
                logger.error(f"### decrypt_user_image decryption failed for mobile {payload.mobile}: {str(decrypt_error)}")
                return {
                    "statuscode": 400,
                    "status": "error",
                    "message": "Failed to decrypt image URL. Malformed or invalid encrypted data."
                }
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"### decrypt_user_image unhandled exception for mobile {payload.mobile}: {str(e)}")
        return {"statuscode": 500, "status": "error", "message": str(e)}


